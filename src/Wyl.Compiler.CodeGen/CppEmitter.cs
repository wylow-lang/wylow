using System.Globalization;
using System.Text;
using Wyl.Compiler.Analysis;
using Wyl.Compiler.Ir;
using Wyl.Compiler.Semantics;
using Wyl.Compiler.Syntax;
using Wyl.Compiler.Text;

namespace Wyl.Compiler.CodeGen;

/// <summary>
/// Translates a checked program to C++. Every safety decision has already been made by the
/// binder and flow analysis; this class must never emit C++ whose behavior is undefined.
/// </summary>
/// <remarks>
/// Structs stay C++ aggregates: constructors become static <c>make</c> functions and field
/// initializers run in <c>make_default</c>, so struct definitions only need their fields' types.
/// Classes derive from <c>wyl::Object</c> and are held through <c>wyl::Ref</c>; their members are
/// defined after every type, so a class may refer to classes declared later.
/// Generics become C++ templates; the binder has already checked every instantiation is valid.
/// </remarks>
public sealed partial class CppEmitter
{
    StringBuilder output = new();
    readonly Dictionary<LocalSymbol, string> localNames = new();
    readonly HashSet<string> usedLocalNames = [];
    int indent;
    int tempCounter;
    TypeSymbol? currentType;
    StdlibSymbols stdlib = new();
    HashSet<TypeSymbol> sharedObjectRoots = [];
    CyclicClasses cycles = null!;

    /// <summary>The program's lowered functions, indexed by the symbol each instruction names.</summary>
    IrFunctions functions = null!;

    /// <summary>What the program's lambdas change, which decides what code nested past a call may see change.</summary>
    IIrLambdaChanges lambdas = null!;

    /// <summary>Whether temporaries are nested back into their uses.</summary>
    bool nest = true;

    public string Emit(BoundProgram program, IrProgram ir, Callees callees, IIrLambdaChanges lambdas, bool nest = true)
    {
        this.lambdas = lambdas;
        functions = ir.Functions;
        this.nest = nest;
        cycles = callees.Cycles;
        recursive = FindRecursive(ir);
        overloaded = FindOverloaded(program);
        unoverridden = FindUnoverridden(program, callees.Overrides);
        var main = program.Main ?? throw new ArgumentException("program has no main function", nameof(program));
        stdlib = program.Stdlib;
        sharedObjectRoots = [.. program.Types.Where(s => s.Kind == TypeKind.Class && s.Interfaces.Count > 0).Select(RootClass)];

        Line($"// Generated by wyl from {program.Package.Name ?? program.Sources[0].Name}. Do not edit.");
        Line("#include \"wyl.h\"");

        if (program.Types.Count > 0)
        {
            Line();
            // The runtime declares what it names, and C++ can't declare it again by its qualified name.
            foreach (var s in program.Types.Where(s => s.RuntimeName is null))
                Line(TemplatePrefix(s.TypeParameters) + $"struct {TypeName(s)};");
        }
        EmitInstantiationTraits();

        Line();
        foreach (var function in program.Functions.Where(f => f.Symbol.ContainingType is null))
            Line(FunctionTemplatePrefix(function.Symbol) + DefinitionSignature(function.Symbol) + ";");

        foreach (var s in DependencyOrder(program.Types))
        {
            Line();
            if (s.Kind == TypeKind.Struct)
                EmitStructDefinition(s);
            else if (s.Kind == TypeKind.Enum)
                EmitEnumDefinition(s);
            else
                EmitObjectDefinition(s);
        }

        foreach (var s in program.Types.Where(s => s.Kind == TypeKind.Struct && s.Type.HasDefaultCode))
        {
            Line();
            EmitDefaultFunction(s);
        }

        foreach (var s in program.Types.Where(s => s.Kind == TypeKind.Class))
        {
            if (s.Destructor is null)
            {
                Line();
                EmitOwnerTemplatePrefix(s);
                Line($"{ObjectType(s.Type)}::~{OwnName(s)}() {{}}");
            }
            foreach (var implementation in s.InheritedImplementations)
            {
                Line();
                EmitForwarder(s, implementation);
            }
        }

        foreach (var s in program.Types.Where(s => !s.IsExtern))
            EmitCollectorMembers(s);

        foreach (var function in program.Functions)
        {
            if (function.Symbol.IsMemberwise)
            {
                foreach (var form in functions.MemberwiseForms(function.Symbol))
                {
                    Line();
                    EmitMemberwiseConstructor(function, form);
                }
                continue;
            }
            Line();
            EmitFunction(function);
        }

        Line();
        Line("int main()");
        Line("{");
        indent++;
        Line("wyl::init();");
        if (main.ReturnType == WylType.Int)
        {
            Line($"return {FunctionName(main)}();");
        }
        else
        {
            Line($"{FunctionName(main)}();");
            Line("return 0;");
        }
        indent--;
        Line("}");
        return output.ToString();
    }

    void Line(string text = "")
    {
        if (text.Length > 0)
            output.Append(' ', indent * 4).Append(text);
        output.Append('\n');
    }

    string NewTemp() => $"tmp_{tempCounter++}";

    // Prefixes keep Wylow names from colliding with C++ keywords, the runtime, and each other.
    string FunctionName(FunctionSymbol function) =>
        "fn_" + (function.Declaration is { } declaration ? ModulePrefix(declaration) : "") + function.Name + OverloadSuffix(function);
    string MethodName(FunctionSymbol method) => (method.IsIndexer ? "wyl_index" : "m_" + ShadowingPrefix(method) + method.Name) + OverloadSuffix(method);

    /// <summary>
    /// A method is named for the first of the class methods it overrides, and that one, if it has
    /// the signature of a base method it can't see (<see cref="FunctionSymbol.Shadows"/>), also for
    /// its class, after its length, so C++ doesn't make it that method's override (spec 06-syntax.md
    /// §6.2). No plain method's name starts with a digit.
    /// </summary>
    static string ShadowingPrefix(FunctionSymbol method)
    {
        var root = method;
        while (root.Overridden.FirstOrDefault(o => o.ContainingType is { Kind: TypeKind.Class }) is { } overridden)
            root = overridden;
        if (root.Shadows is null)
            return "";
        var owner = QualifiedName(root.ContainingType!);
        return $"{owner.Length}{owner}_";
    }
    static string FieldName(FieldSymbol field) => "f_" + field.Name;
    static string TypeParameterName(TypeParameterSymbol parameter) => "t_" + parameter.Name;

    static string TypeName(TypeSymbol s) => s.RuntimeName ?? s.Kind switch
    {
        TypeKind.Struct => "s_" + QualifiedName(s),
        TypeKind.Enum => "e_" + QualifiedName(s),
        TypeKind.Class => "c_" + QualifiedName(s),
        _ => "i_" + QualifiedName(s),
    };

    static string QualifiedName(TypeSymbol s) => ModulePrefix(s.Declaration) + s.Name;

    /// <summary>
    /// What a top-level name's C++ name starts with, so equal names in different modules differ in
    /// C++: each name of its module's path after its length, with the package's for the standard
    /// library (<c>3std5panic</c>), then, for a file-private name in a module of several files,
    /// which may each have one of that name, <c>0</c> and the file's place in the module. Nothing at
    /// all in a lone file, or in the program's root module but for those private names. No two
    /// prefixes are equal, and none can begin a plain name, since an identifier never starts with a
    /// digit. Only the program's own package goes unnamed, so a dependency's names will be qualified
    /// by its package like <c>std</c>'s.
    /// </summary>
    static string ModulePrefix(Declaration declaration)
    {
        var source = declaration.Location.Source;
        var module = source.Module;
        IEnumerable<string> names = module.Package.IsStd ? ["std", .. module.Path] : module.Path;
        var prefix = string.Concat(names.Select(n => $"{n.Length}{n}"));
        if (declaration.Visibility == Visibility.File && module.Files.Count > 1)
            prefix += "0" + module.Files.ToList().IndexOf(source).ToString(CultureInfo.InvariantCulture);
        return prefix.Length == 0 ? "" : prefix + "_";
    }

    /// <summary>
    /// Parameters keep their names, so that declarations and definitions agree. Other locals get a
    /// suffix where one function would otherwise declare a name twice in a C++ scope, as pattern
    /// names hoisted out of different switch cases can.
    /// </summary>
    string LocalName(LocalSymbol local)
    {
        if (localNames.TryGetValue(local, out var name))
            return name;
        if (local.IsTemporary)
        {
            name = NewTemp();
        }
        else
        {
            name = "l_" + local.Name;
            for (int i = 2; !local.IsParameter && !usedLocalNames.Add(name); i++)
                name = $"l_{local.Name}_{i}";
        }
        localNames[local] = name;
        return name;
    }

    static string TemplatePrefix(IReadOnlyList<TypeParameterSymbol> parameters) => parameters.Count == 0
        ? ""
        : $"template <{string.Join(", ", parameters.Select(p => "class " + TypeParameterName(p)))}> ";

    static string TypeArgumentList(IReadOnlyList<WylType> arguments) =>
        arguments.Count == 0 ? "" : $"<{string.Join(", ", arguments.Select(CppType))}>";

    /// <summary>The C++ class of a struct, class, or interface type, without the <c>wyl::Ref</c> around objects.</summary>
    static string ObjectType(WylType type) => TypeName(type.Symbol!) + TypeArgumentList(type.TypeArguments);

    static string CppType(WylType type)
    {
        if (type is TypeParameterType parameter) return TypeParameterName(parameter.Parameter);
        if (type is PointerType pointer) return CppType(pointer.Element) + "*";
        // A reference that may refer to nothing is a pointer, null when it refers to nothing.
        if (type is NullableReferenceType reference) return (reference.Kind == RefKind.In ? "const " : "") + CppType(reference.Referenced) + "*";
        if (type is FixedArrayType array) return $"std::array<{CppType(array.Element)}, {array.Length}>";
        if (type.IsReference) return $"wyl::Ref<{ObjectType(type)}>";
        // A local holding a lambda is `auto`, and a template parameter its own type; see CppEmitter.Lambdas.cs.
        if (type is FunctionType function) return $"wyl::{(function.IsEscaping ? "Function" : "FunctionRef")}<{FunctionSignature(function)}>";
        // `T?` is a reference or an Optional depending on what `T` stands for.
        if (type.IsNullableValue) return type.NonNull.IsTypeParameter ? $"wyl::Nullable<{CppType(type.NonNull)}>" : $"wyl::Optional<{CppType(type.NonNull)}>";
        if (type.IsStructOrEnum) return ObjectType(type);
        if (type == WylType.Void) return "void";
        if (type == WylType.Bool) return "bool";
        if (type == WylType.SByte) return "int8_t";
        if (type == WylType.Byte) return "uint8_t";
        if (type == WylType.Short) return "int16_t";
        if (type == WylType.UShort) return "uint16_t";
        if (type == WylType.Int) return "int32_t";
        if (type == WylType.UInt) return "uint32_t";
        if (type == WylType.Long) return "int64_t";
        if (type == WylType.ULong) return "uint64_t";
        if (type == WylType.NInt) return "intptr_t";
        if (type == WylType.NUInt) return "uintptr_t";
        if (type == WylType.Char) return "char32_t";
        if (type == WylType.Float) return "float";
        if (type == WylType.Double) return "double";
        if (type == WylType.String) return "wyl::String";
        throw new InvalidOperationException($"no C++ type for '{type}'");
    }

    /// <summary>
    /// A <c>const</c> reference to a value of the type, as an <c>in</c> parameter or a borrow: the
    /// <c>const</c> qualifies the value itself, so for a pointer it is written after the <c>*</c>.
    /// </summary>
    static string ConstReferenceType(WylType type) =>
        type.IsPointer || type.IsNullableReference ? $"{CppType(type)} const&" : $"const {CppType(type)}&";
}
