using System.Globalization;
using System.Text;
using Vpl.Compiler.Semantics;
using Vpl.Compiler.Syntax;
using Vpl.Compiler.Text;

namespace Vpl.Compiler.CodeGen;

/// <summary>
/// Translates a checked program to C++. Every safety decision has already been made by the
/// binder and flow analysis; this class must never emit C++ whose behavior is undefined.
/// </summary>
/// <remarks>
/// Structs stay C++ aggregates: constructors become static <c>make</c> functions and field
/// initializers run in <c>make_default</c>, so struct definitions only need their fields' types.
/// Classes derive from <c>vpl::Object</c> and are held through <c>vpl::Ref</c>; their members are
/// defined after every type, so a class may refer to classes declared later.
/// Generics become C++ templates; the binder has already checked every instantiation is valid.
/// </remarks>
public sealed partial class CppEmitter
{
    enum Context { Free, Method, StructConstructor, ClassMember }

    /// <summary>
    /// An operand of a call or operator. <see cref="ByReference"/> operands bind to their place.
    /// <see cref="PinRoot"/> is an object owning that place, and <see cref="PinValue"/> marks an
    /// object receiver; both are held by a strong reference while the operation runs.
    /// <see cref="Keep"/> marks a by-value argument whose copy must be owned by the caller; see <c>vpl::keep</c>.
    /// <see cref="Copy"/> marks a value that must be copied out of its place, since what it is passed
    /// to refers to it while the place may change.
    /// </summary>
    readonly record struct Operand(
        BoundExpression Expression,
        bool ByReference,
        BoundExpression? PinRoot = null,
        bool PinValue = false,
        bool Keep = false,
        bool Copy = false);

    StringBuilder output = new();
    readonly Dictionary<TypeSymbol, bool> needsDefaultFunction = new();
    readonly Dictionary<LocalSymbol, string> localNames = new();
    readonly HashSet<string> usedLocalNames = [];
    readonly Dictionary<BoundExpression, string> replacements = new(ReferenceEqualityComparer.Instance);
    int indent;
    int tempCounter;
    Context context;
    TypeSymbol? currentType;
    FunctionSymbol? currentFunction;
    StdlibSymbols stdlib = new();
    List<TypeSymbol> borrowableClasses = [];
    HashSet<TypeSymbol> sharedObjectRoots = [];
    CyclicClasses cycles = null!;

    public string Emit(BoundProgram program, CyclicClasses cycles)
    {
        this.cycles = cycles;
        recursive = FindRecursive(program);
        overloaded = FindOverloaded(program);
        unoverridden = FindUnoverridden(program);
        lambdaChanged = FindLambdaChanged(program);
        var main = program.Main ?? throw new ArgumentException("program has no main function", nameof(program));
        stdlib = program.Stdlib;
        borrowableClasses = [.. program.Types.Where(s => s.Kind == TypeKind.Class && stdlib.Borrowable is { } borrowable && Conversions.IsSubtype(s.Type, borrowable.Type))];
        sharedObjectRoots = [.. program.Types.Where(s => s.Kind == TypeKind.Class && s.Interfaces.Count > 0).Select(RootClass)];

        Line($"// Generated by vpl from {program.Source.FileName}. Do not edit.");
        Line("#include \"vpl.h\"");

        if (program.Types.Count > 0)
        {
            Line();
            foreach (var s in program.Types.Where(s => !s.IsExtern))
                Line(TemplatePrefix(s.TypeParameters) + $"struct {TypeName(s)};");
        }
        EmitInstantiationTraits();

        Line();
        foreach (var function in program.Functions.Where(f => f.Symbol.ContainingType is null))
            Line(FunctionTemplatePrefix(function.Symbol) + DefinitionSignature(function.Symbol) + ";");

        foreach (var s in DependencyOrder(program.Types))
        {
            Line();
            if (s.Kind == TypeKind.Struct)
                EmitStructDefinition(s);
            else if (s.Kind == TypeKind.Enum)
                EmitEnumDefinition(s);
            else
                EmitObjectDefinition(s);
        }

        foreach (var s in program.Types.Where(s => s.Kind == TypeKind.Struct && NeedsDefaultFunction(s)))
        {
            Line();
            EmitDefaultFunction(s);
        }

        foreach (var s in program.Types.Where(s => s.Kind == TypeKind.Class))
        {
            if (s.Destructor is null)
            {
                Line();
                EmitOwnerTemplatePrefix(s);
                Line($"{ObjectType(s.Type)}::~{TypeName(s)}() {{}}");
            }
            foreach (var implementation in s.InheritedImplementations)
            {
                Line();
                EmitForwarder(s, implementation);
            }
        }

        foreach (var s in program.Types.Where(s => !s.IsExtern))
            EmitCollectorMembers(s);

        foreach (var function in program.Functions)
        {
            Line();
            EmitFunction(function);
        }

        Line();
        Line("int main()");
        Line("{");
        indent++;
        Line("vpl::init();");
        if (main.ReturnType == VplType.Int)
        {
            Line($"return {FunctionName(main)}();");
        }
        else
        {
            Line($"{FunctionName(main)}();");
            Line("return 0;");
        }
        indent--;
        Line("}");
        return output.ToString();
    }

    void Line(string text = "")
    {
        if (text.Length > 0)
            output.Append(' ', indent * 4).Append(text);
        output.Append('\n');
    }

    string NewTemp() => $"tmp_{tempCounter++}";

    // Prefixes keep VPL names from colliding with C++ keywords, the runtime, and each other.
    string FunctionName(FunctionSymbol function) => "fn_" + function.Name + OverloadSuffix(function);
    string MethodName(FunctionSymbol method) => (method.IsIndexer ? "vpl_index" : "m_" + method.Name) + OverloadSuffix(method);
    static string FieldName(FieldSymbol field) => "f_" + field.Name;
    static string TypeParameterName(TypeParameterSymbol parameter) => "t_" + parameter.Name;

    static string TypeName(TypeSymbol s) => s.Kind switch
    {
        TypeKind.Struct when s.IsExtern => "vpl::" + s.Name,
        TypeKind.Struct => "s_" + s.Name,
        TypeKind.Enum => "e_" + s.Name,
        TypeKind.Class => "c_" + s.Name,
        _ => "i_" + s.Name,
    };

    /// <summary>
    /// Parameters keep their names, so that declarations and definitions agree. Other locals get a
    /// suffix where one function would otherwise declare a name twice in a C++ scope, as pattern
    /// names hoisted out of different switch cases can.
    /// </summary>
    string LocalName(LocalSymbol local)
    {
        if (localNames.TryGetValue(local, out var name))
            return name;
        if (local.IsTemporary)
        {
            name = NewTemp();
        }
        else
        {
            name = "l_" + local.Name;
            for (int i = 2; !local.IsParameter && !usedLocalNames.Add(name); i++)
                name = $"l_{local.Name}_{i}";
        }
        localNames[local] = name;
        return name;
    }

    static string TemplatePrefix(IReadOnlyList<TypeParameterSymbol> parameters) => parameters.Count == 0
        ? ""
        : $"template <{string.Join(", ", parameters.Select(p => "class " + TypeParameterName(p)))}> ";

    static string TypeArgumentList(IReadOnlyList<VplType> arguments) =>
        arguments.Count == 0 ? "" : $"<{string.Join(", ", arguments.Select(CppType))}>";

    /// <summary>The C++ class of a struct, class, or interface type, without the <c>vpl::Ref</c> around objects.</summary>
    static string ObjectType(VplType type) => TypeName(type.Symbol!) + TypeArgumentList(type.TypeArguments);

    static string CppType(VplType type)
    {
        if (type.TypeParameter is { } parameter) return TypeParameterName(parameter);
        if (type.IsPointer) return CppType(type.ElementType!) + "*";
        if (type.IsFixedArray) return $"std::array<{CppType(type.ElementType!)}, {type.FixedLength}>";
        if (type.IsReference) return $"vpl::Ref<{ObjectType(type)}>";
        // A local holding a lambda is `auto`, and a template parameter its own type; see CppEmitter.Lambdas.cs.
        if (type.IsFunction) return $"vpl::{(type.IsEscaping ? "Function" : "FunctionRef")}<{FunctionSignature(type)}>";
        // `T?` is a reference or an Optional depending on what `T` stands for.
        if (type.IsNullableValue) return type.NonNull.IsTypeParameter ? $"vpl::Nullable<{CppType(type.NonNull)}>" : $"vpl::Optional<{CppType(type.NonNull)}>";
        if (type.IsStructOrEnum) return ObjectType(type);
        if (type == VplType.Void) return "void";
        if (type == VplType.Bool) return "bool";
        if (type == VplType.Int) return "int32_t";
        if (type == VplType.Long) return "int64_t";
        if (type == VplType.Float) return "float";
        if (type == VplType.Double) return "double";
        if (type == VplType.String) return "vpl::String";
        throw new InvalidOperationException($"no C++ type for '{type}'");
    }
}
