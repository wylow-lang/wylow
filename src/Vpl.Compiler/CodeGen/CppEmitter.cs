using System.Globalization;
using System.Text;
using Vpl.Compiler.Semantics;
using Vpl.Compiler.Syntax;
using Vpl.Compiler.Text;

namespace Vpl.Compiler.CodeGen;

/// <summary>
/// Translates a checked program to C++. Every safety decision has already been made by the
/// binder and flow analysis; this class must never emit C++ whose behavior is undefined.
/// </summary>
/// <remarks>
/// Structs stay C++ aggregates: constructors become static <c>make</c> functions and field
/// initializers run in <c>make_default</c>, so struct definitions only need their fields' types.
/// Classes derive from <c>vpl::Object</c> and are held through <c>vpl::Ref</c>; their members are
/// defined after every type, so a class may refer to classes declared later.
/// Generics become C++ templates; the binder has already checked every instantiation is valid.
/// </remarks>
public sealed class CppEmitter
{
    enum Context { Free, Method, StructConstructor, ClassMember }

    /// <summary>
    /// An operand of a call or operator. <see cref="ByReference"/> operands bind to their place.
    /// <see cref="PinRoot"/> is an object owning that place, and <see cref="PinValue"/> marks an
    /// object receiver; both are held by a strong reference while the operation runs.
    /// <see cref="Keep"/> marks a by-value argument whose copy must be owned by the caller; see <c>vpl::keep</c>.
    /// </summary>
    readonly record struct Operand(
        BoundExpression Expression,
        bool ByReference,
        BoundExpression? PinRoot = null,
        bool PinValue = false,
        bool Keep = false);

    readonly StringBuilder output = new();
    readonly Dictionary<TypeSymbol, bool> needsDefaultFunction = new();
    readonly Dictionary<LocalSymbol, string> temporaryNames = new();
    readonly Dictionary<BoundExpression, string> replacements = new(ReferenceEqualityComparer.Instance);
    int indent;
    int tempCounter;
    Context context;
    TypeSymbol? currentType;

    public string Emit(BoundProgram program)
    {
        var main = program.Main ?? throw new ArgumentException("program has no main function", nameof(program));

        Line($"// Generated by vpl from {program.Source.FileName}. Do not edit.");
        Line("#include \"vpl.h\"");

        if (program.Types.Count > 0)
        {
            Line();
            foreach (var s in program.Types)
                Line(TemplatePrefix(s.TypeParameters) + $"struct {TypeName(s)};");
        }

        Line();
        foreach (var function in program.Functions.Where(f => f.Symbol.ContainingType is null))
            Line(TemplatePrefix(function.Symbol.TypeParameters) + DefinitionSignature(function.Symbol) + ";");

        foreach (var s in DependencyOrder(program.Types))
        {
            Line();
            if (s.Kind == TypeKind.Struct)
                EmitStructDefinition(s);
            else
                EmitObjectDefinition(s);
        }

        foreach (var s in program.Types.Where(s => s.Kind == TypeKind.Struct && NeedsDefaultFunction(s)))
        {
            Line();
            EmitDefaultFunction(s);
        }

        foreach (var s in program.Types.Where(s => s.Kind == TypeKind.Class))
        {
            if (s.Destructor is null)
            {
                Line();
                EmitOwnerTemplatePrefix(s);
                Line($"{ObjectType(s.Type)}::~{TypeName(s)}() {{}}");
            }
            foreach (var implementation in s.InheritedImplementations)
            {
                Line();
                EmitForwarder(s, implementation);
            }
        }

        foreach (var function in program.Functions)
        {
            Line();
            EmitFunction(function);
        }

        Line();
        Line("int main()");
        Line("{");
        indent++;
        Line("vpl::init();");
        if (main.ReturnType == VplType.Int)
        {
            Line($"return {FunctionName(main)}();");
        }
        else
        {
            Line($"{FunctionName(main)}();");
            Line("return 0;");
        }
        indent--;
        Line("}");
        return output.ToString();
    }

    void Line(string text = "")
    {
        if (text.Length > 0)
            output.Append(' ', indent * 4).Append(text);
        output.Append('\n');
    }

    string NewTemp() => $"tmp_{tempCounter++}";

    // Prefixes keep VPL names from colliding with C++ keywords, the runtime, and each other.
    static string FunctionName(FunctionSymbol function) => "fn_" + function.Name;
    static string MethodName(FunctionSymbol method) => "m_" + method.Name;
    static string FieldName(FieldSymbol field) => "f_" + field.Name;
    static string TypeParameterName(TypeParameterSymbol parameter) => "t_" + parameter.Name;

    static string TypeName(TypeSymbol s) => s.Kind switch
    {
        TypeKind.Struct => "s_" + s.Name,
        TypeKind.Class => "c_" + s.Name,
        _ => "i_" + s.Name,
    };

    string LocalName(LocalSymbol local)
    {
        if (!local.IsTemporary)
            return "l_" + local.Name;
        if (!temporaryNames.TryGetValue(local, out var name))
            temporaryNames[local] = name = NewTemp();
        return name;
    }

    static string TemplatePrefix(IReadOnlyList<TypeParameterSymbol> parameters) => parameters.Count == 0
        ? ""
        : $"template <{string.Join(", ", parameters.Select(p => "class " + TypeParameterName(p)))}> ";

    static string TypeArgumentList(IReadOnlyList<VplType> arguments) =>
        arguments.Count == 0 ? "" : $"<{string.Join(", ", arguments.Select(CppType))}>";

    /// <summary>The C++ class of a struct, class, or interface type, without the <c>vpl::Ref</c> around objects.</summary>
    static string ObjectType(VplType type) => TypeName(type.Symbol!) + TypeArgumentList(type.TypeArguments);

    static string CppType(VplType type)
    {
        if (type.TypeParameter is { } parameter) return TypeParameterName(parameter);
        if (type.IsReference) return $"vpl::Ref<{ObjectType(type)}>";
        if (type.IsStruct) return ObjectType(type);
        if (type == VplType.Void) return "void";
        if (type == VplType.Bool) return "bool";
        if (type == VplType.Int) return "int32_t";
        if (type == VplType.Long) return "int64_t";
        if (type == VplType.Float) return "float";
        if (type == VplType.Double) return "double";
        if (type == VplType.String) return "vpl::String";
        throw new InvalidOperationException($"no C++ type for '{type}'");
    }

    // ---- Type definitions ----

    /// <summary>
    /// Orders definitions so each comes after its base types and every struct its fields hold by
    /// value, including in type arguments. Objects are held by reference and need no ordering.
    /// </summary>
    static List<TypeSymbol> DependencyOrder(IReadOnlyList<TypeSymbol> types)
    {
        var ordered = new List<TypeSymbol>();
        var visited = new HashSet<TypeSymbol>();

        void VisitType(VplType type)
        {
            if (type.IsReference)
                return;
            if (type.Symbol is { } s)
                Visit(s);
            foreach (var argument in type.TypeArguments)
                VisitType(argument);
        }

        void Visit(TypeSymbol s)
        {
            if (!visited.Add(s))
                return;
            if (s.BaseType is { } baseType)
                Visit(baseType.Symbol!);
            foreach (var iface in s.Kind == TypeKind.Struct ? [] : s.Interfaces)
                Visit(iface.Symbol!);
            foreach (var field in s.Fields)
                VisitType(field.Type);
            ordered.Add(s);
        }

        foreach (var s in types)
            Visit(s);
        return ordered;
    }

    /// <summary>
    /// Whether default construction must run code rather than just zero-initialize. Generic structs
    /// always get a <c>make_default</c>, since their type arguments may need one.
    /// </summary>
    bool NeedsDefaultFunction(TypeSymbol s)
    {
        if (!needsDefaultFunction.TryGetValue(s, out bool needs))
        {
            needsDefaultFunction[s] = false;
            needs = s.IsGeneric || s.Fields.Any(f => f.Initializer is not null || NeedsDefaultCode(f.Type));
            needsDefaultFunction[s] = needs;
        }
        return needs;
    }

    bool NeedsDefaultCode(VplType type) =>
        type.IsTypeParameter || (type.IsStruct && NeedsDefaultFunction(type.Symbol!));

    string DefaultValue(VplType type)
    {
        if (type.IsTypeParameter)
            return $"vpl::default_value<{CppType(type)}>()";
        return type.IsStruct && NeedsDefaultFunction(type.Symbol!) ? $"{CppType(type)}::make_default()" : $"{CppType(type)}{{}}";
    }

    void EmitStructDefinition(TypeSymbol s)
    {
        var name = TypeName(s);
        if (s.IsGeneric)
            Line(TemplatePrefix(s.TypeParameters).TrimEnd());
        Line($"struct {name}");
        Line("{");
        indent++;
        foreach (var field in s.Fields)
            Line($"{CppType(field.Type)} {FieldName(field)}{{}};");
        if (NeedsDefaultFunction(s))
            Line($"static {name} make_default();");
        foreach (var member in s.Members)
            Line(TemplatePrefix(member.TypeParameters) + MemberDeclaration(member) + ";");
        // In a template, a defaulted == whose members lack == is deleted rather than an error.
        if (s.IsGeneric || Conversions.SupportsEquality(s.Type))
            Line($"bool operator==(const {name}&) const = default;");
        indent--;
        Line("};");
    }

    /// <summary>Classes and interfaces. Interfaces inherit virtually so that a class has one copy of each.</summary>
    void EmitObjectDefinition(TypeSymbol s)
    {
        var bases = new List<string>();
        if (s.BaseType is { } baseType)
            bases.Add(ObjectType(baseType));
        else
            bases.Add("virtual vpl::Object");
        bases.AddRange(s.Interfaces.Select(i => "virtual " + ObjectType(i)));

        if (s.IsGeneric)
            Line(TemplatePrefix(s.TypeParameters).TrimEnd());
        Line($"struct {TypeName(s)} : {string.Join(", ", bases)}");
        Line("{");
        indent++;
        foreach (var field in s.Fields)
        {
            Line(field.IsWeak
                ? $"vpl::Weak<{ObjectType(field.Type)}> {FieldName(field)};"
                : $"{CppType(field.Type)} {FieldName(field)}{{}};");
        }
        if (s.Kind == TypeKind.Class)
        {
            if (s.Constructors.Count == 0)
                Line($"{TypeName(s)}();");
            // Declared here and defined after every type, where the field types are complete.
            if (s.Destructor is null)
                Line($"~{TypeName(s)}() override;");
        }
        foreach (var member in s.Members)
        {
            if (member.IsAbstract)
                EmitAbstractStub(member);
            else
                Line(TemplatePrefix(member.TypeParameters) + MemberDeclaration(member) + ";");
        }
        foreach (var implementation in s.InheritedImplementations)
            Line($"{CppType(implementation.ReturnType)} {MethodName(implementation.Symbol)}({Parameters(implementation)}) override;");
        indent--;
        Line("};");
    }

    /// <summary>
    /// Abstract methods get a body so that no call is ever a C++ pure virtual call: during a base
    /// class constructor or destructor the object is still the base class, and calling an abstract
    /// method then panics.
    /// </summary>
    void EmitAbstractStub(FunctionSymbol method)
    {
        var parameterTypes = string.Join(", ", method.Parameters.Select(p => ParameterType(p.Type, p.RefKind)));
        var location = SourceLocation(method.Declaration!.NameLocation);
        var message = CppStringLiteral($"abstract method '{method.ContainingType!.Name}.{method.Name}' called during construction or destruction");
        Line($"virtual {CppType(method.ReturnType)} {MethodName(method)}({parameterTypes}) {{ vpl::panic({message}, {location}); }}");
    }

    void EmitDefaultFunction(TypeSymbol s)
    {
        var type = CppType(s.Type);
        context = Context.Free;
        if (s.IsGeneric)
            Line(TemplatePrefix(s.TypeParameters).TrimEnd());
        Line($"{type} {type}::make_default()");
        Line("{");
        indent++;
        Line($"{type} self{{}};");
        foreach (var field in s.Fields)
        {
            if (field.Initializer is { } initializer)
                Line($"self.{FieldName(field)} = {Expression(initializer)};");
            else if (NeedsDefaultCode(field.Type))
                Line($"self.{FieldName(field)} = {DefaultValue(field.Type)};");
        }
        Line("return self;");
        indent--;
        Line("}");
    }

    /// <summary>Connects an interface method to the base class method that implements it.</summary>
    void EmitForwarder(TypeSymbol s, MethodReference implementation)
    {
        EmitOwnerTemplatePrefix(s);
        var method = implementation.Symbol;
        Line($"{CppType(implementation.ReturnType)} {ObjectType(s.Type)}::{MethodName(method)}({Parameters(implementation)})");
        Line("{");
        var arguments = string.Join(", ", method.Parameters.Select(LocalName));
        Line($"    return this->{ObjectType(implementation.Owner!)}::{MethodName(method)}({arguments});");
        Line("}");
    }

    void EmitOwnerTemplatePrefix(TypeSymbol s)
    {
        if (s.IsGeneric)
            Line(TemplatePrefix(s.TypeParameters).TrimEnd());
    }

    // ---- Functions ----

    static string ParameterType(VplType type, RefKind refKind) => refKind switch
    {
        RefKind.Ref => CppType(type) + "&",
        RefKind.In => $"const {CppType(type)}&",
        _ => CppType(type),
    };

    string Parameters(FunctionSymbol function) =>
        string.Join(", ", function.Parameters.Select(p => $"{ParameterType(p.Type, p.RefKind)} {LocalName(p)}"));

    string Parameters(MethodReference method) =>
        string.Join(", ", method.Symbol.Parameters.Select((p, i) => $"{ParameterType(method.ParameterType(i), p.RefKind)} {LocalName(p)}"));

    string MemberDeclaration(FunctionSymbol member)
    {
        var owner = member.ContainingType!;
        if (member.IsConstructor)
        {
            return owner.Kind == TypeKind.Struct
                ? $"static {TypeName(owner)} make({Parameters(member)})"
                : $"{TypeName(owner)}({Parameters(member)})";
        }
        if (member.IsDestructor)
            return $"~{TypeName(owner)}() override";
        var signature = $"{CppType(member.ReturnType)} {MethodName(member)}({Parameters(member)})";
        if (member.IsStatic)
            return "static " + signature;
        if (member.IsVirtual)
            return "virtual " + signature;
        if (member.IsOverride)
            return signature + (member.IsFinal ? " override final" : " override");
        return signature + (member.IsReadOnly ? " const" : "");
    }

    string DefinitionSignature(FunctionSymbol function)
    {
        if (function.ContainingType is not { } s)
            return $"{CppType(function.ReturnType)} {FunctionName(function)}({Parameters(function)})";
        var owner = ObjectType(s.Type);
        if (function.IsConstructor)
        {
            return s.Kind == TypeKind.Struct
                ? $"{owner} {owner}::make({Parameters(function)})"
                : $"{owner}::{TypeName(s)}({Parameters(function)})";
        }
        if (function.IsDestructor)
            return $"{owner}::~{TypeName(s)}()";
        var signature = $"{CppType(function.ReturnType)} {owner}::{MethodName(function)}({Parameters(function)})";
        return function.IsReadOnly ? signature + " const" : signature;
    }

    void EmitFunction(BoundFunction function)
    {
        var symbol = function.Symbol;
        currentType = symbol.ContainingType;
        bool isClassMember = currentType is { Kind: not TypeKind.Struct };
        context = isClassMember && !symbol.IsStatic ? Context.ClassMember
            : symbol.IsConstructor ? Context.StructConstructor
            : symbol.IsInstanceMethod ? Context.Method
            : Context.Free;

        if (currentType is { IsGeneric: true } owner)
            Line(TemplatePrefix(owner.TypeParameters).TrimEnd());
        if (symbol.IsGeneric)
            Line(TemplatePrefix(symbol.TypeParameters).TrimEnd());
        Line(DefinitionSignature(symbol));

        var statements = function.Body.Statements;
        if (symbol.IsConstructor && isClassMember && statements.FirstOrDefault() is BoundSuperCall super)
        {
            // Braces evaluate the arguments left to right.
            var arguments = string.Join(", ", super.Arguments.Select(a =>
                !IsStable(a) && MayHoldReferences(a.Type) ? $"vpl::keep({Expression(a)})" : Expression(a)));
            Line($"    : {ObjectType(super.Constructor.Owner!)}{{{arguments}}}");
            statements = [.. statements.Skip(1)];
        }

        Line("{");
        indent++;
        if (symbol.IsConstructor && isClassMember)
        {
            foreach (var field in currentType!.Fields)
            {
                if (field.Initializer is { } initializer)
                    Line($"this->{FieldName(field)} = {Expression(initializer)};");
                else if (!field.IsWeak && NeedsDefaultCode(field.Type) && !field.Type.IsTypeParameter)
                    Line($"this->{FieldName(field)} = {DefaultValue(field.Type)};");
            }
        }
        else if (symbol.IsConstructor)
        {
            var type = currentType!.Type;
            Line($"{CppType(type)} self = {DefaultValue(type)};");
        }
        foreach (var statement in statements)
            Statement(statement);
        if (symbol.IsConstructor && !isClassMember)
        {
            Line("return self;");
        }
        else if (symbol.ReturnType != VplType.Void)
        {
            var body = function.Body.Location;
            Line($"vpl::unreachable({SourceLocation(body with { Span = new TextSpan(body.Span.End - 1, 1) })});");
        }
        indent--;
        Line("}");
        context = Context.Free;
        currentType = null;
    }

    // ---- Statements ----

    void Statement(BoundStatement statement)
    {
        switch (statement)
        {
            case BoundBlock block:
                Line("{");
                indent++;
                foreach (var s in block.Statements)
                    Statement(s);
                indent--;
                Line("}");
                break;
            case BoundVariableDeclaration declaration:
                DeclarePatternLocals(declaration.Initializer);
                var initializer = declaration.Initializer is null ? "{}" : " = " + Expression(declaration.Initializer);
                Line($"{CppType(declaration.Local.Type)} {LocalName(declaration.Local)}{initializer};");
                break;
            case BoundAssignment assignment:
                DeclarePatternLocals(assignment.Value);
                Line(SimpleStatement(statement) + ";");
                break;
            case BoundExpressionStatement expressionStatement:
                DeclarePatternLocals(expressionStatement.Expression);
                Line(SimpleStatement(statement) + ";");
                break;
            case BoundIf ifStatement:
                OpenPatternScope(ifStatement.Condition);
                Line($"if ({Expression(ifStatement.Condition)})");
                Statement(ifStatement.Then);
                if (ifStatement.Else is not null)
                {
                    Line("else");
                    Statement(ifStatement.Else);
                }
                ClosePatternScope(ifStatement.Condition);
                break;
            case BoundWhile whileStatement:
                OpenPatternScope(whileStatement.Condition);
                Line($"while ({Expression(whileStatement.Condition)})");
                Statement(whileStatement.Body);
                ClosePatternScope(whileStatement.Condition);
                break;
            case BoundFor forStatement:
                Line("{");
                indent++;
                if (forStatement.Initializer is not null)
                    Statement(forStatement.Initializer);
                DeclarePatternLocals(forStatement.Condition);
                var condition = forStatement.Condition is null ? "" : Expression(forStatement.Condition);
                var update = forStatement.Update is null ? "" : SimpleStatement(forStatement.Update);
                Line($"for (; {condition}; {update})");
                Statement(forStatement.Body);
                indent--;
                Line("}");
                break;
            case BoundReturn returnStatement:
                DeclarePatternLocals(returnStatement.Value);
                if (context == Context.StructConstructor)
                    Line("return self;");
                else
                    Line(returnStatement.Value is null ? "return;" : $"return {Expression(returnStatement.Value)};");
                break;
            case BoundBreak:
                Line("break;");
                break;
            case BoundContinue:
                Line("continue;");
                break;
            default:
                throw new InvalidOperationException($"unexpected statement {statement.GetType().Name}");
        }
    }

    static IEnumerable<LocalSymbol> PatternLocals(BoundExpression? expression) => expression switch
    {
        null => [],
        BoundIs { Binding: { } binding } pattern => [.. PatternLocals(pattern.Operand), binding],
        _ => Children(expression).SelectMany(PatternLocals),
    };

    void DeclarePatternLocals(BoundExpression? expression)
    {
        foreach (var local in PatternLocals(expression))
            Line($"{CppType(local.Type)} {LocalName(local)};");
    }

    // Pattern names in a condition are scoped to the statement, as in VPL.
    void OpenPatternScope(BoundExpression condition)
    {
        if (!PatternLocals(condition).Any())
            return;
        Line("{");
        indent++;
        DeclarePatternLocals(condition);
    }

    void ClosePatternScope(BoundExpression condition)
    {
        if (!PatternLocals(condition).Any())
            return;
        indent--;
        Line("}");
    }

    string SimpleStatement(BoundStatement statement) => statement switch
    {
        BoundAssignment assignment => Assignment(assignment),
        BoundExpressionStatement expressionStatement => Expression(expressionStatement.Expression),
        _ => throw new InvalidOperationException($"unexpected simple statement {statement.GetType().Name}"),
    };

    /// <summary>
    /// C++17 evaluates the right side of '=' before the left. That only matters when the target
    /// goes through an object that the value's evaluation could replace; that object is then
    /// pinned first, which also keeps it alive for the store.
    /// </summary>
    string Assignment(BoundAssignment assignment)
    {
        var root = PinRoot(assignment.Target);
        if (root is null || !(HasEffects(assignment.Value) || Writes(assignment.Value)))
            return Store(assignment);

        var pin = NewTemp();
        var rootText = Expression(root);
        replacements[root] = pin;
        var store = Store(assignment);
        replacements.Remove(root);
        return $"[&] {{ auto {pin} = {rootText}; {store}; }}()";
    }

    string Store(BoundAssignment assignment)
    {
        var target = Place(assignment.Target);
        var value = Expression(assignment.Value);
        var type = assignment.Target.Type;
        bool plain = type.IsReference || !(type.IsStruct || type.IsTypeParameter) || assignment.Target is BoundFieldAccess { Field.IsWeak: true };
        return plain ? $"{target} = {value}" : $"vpl::assign({target}, {value})";
    }

    // ---- Expressions ----

    string Expression(BoundExpression expression)
    {
        if (replacements.TryGetValue(expression, out var replacement))
            return replacement;
        return expression switch
        {
            BoundLiteral literal => Literal(literal),
            BoundNullLiteral => "nullptr",
            BoundLocalAccess access => LocalName(access.Local),
            BoundThis => This(),
            BoundFieldAccess field => FieldAccess(field) + (field.Field.IsWeak ? ".get()" : ""),
            BoundUnary unary => Unary(unary),
            BoundBinary binary => Binary(binary),
            BoundCall call => Call(call),
            BoundConstruction construction => Construction(construction),
            BoundNew creation => New(creation),
            BoundConversion conversion => Conversion(conversion),
            BoundConditional conditional =>
                $"({Expression(conditional.Condition)} ? {Expression(conditional.WhenTrue)} : {Expression(conditional.WhenFalse)})",
            BoundNonNull nonNull => $"vpl::unwrap({Expression(nonNull.Operand)}, {SourceLocation(nonNull.Location)})",
            BoundCoalesce coalesce => Coalesce(coalesce),
            BoundConditionalAccess access => ConditionalAccess(access),
            BoundIs pattern => Is(pattern),
            _ => throw new InvalidOperationException($"unexpected expression {expression.GetType().Name}"),
        };
    }

    /// <summary>An expression used as a place to store to or bind a reference to; weak fields stay <c>vpl::Weak</c>.</summary>
    string Place(BoundExpression expression) =>
        expression is BoundFieldAccess field && !replacements.ContainsKey(expression) ? FieldAccess(field) : Expression(expression);

    string This() => context switch
    {
        Context.StructConstructor => "self",
        Context.ClassMember => $"vpl::Ref<{ObjectType(currentType!.Type)}>(this)",
        _ => "(*this)",
    };

    string FieldAccess(BoundFieldAccess field)
    {
        if (field.Receiver is BoundThis && !replacements.ContainsKey(field.Receiver))
            return (context == Context.StructConstructor ? "self." : "this->") + FieldName(field.Field);
        var receiver = Expression(field.Receiver);
        return receiver + (field.Receiver.Type.IsReference ? "->" : ".") + FieldName(field.Field);
    }

    /// <summary>
    /// The object whose storage holds a place, when it may die while the place is in use: the
    /// nearest object in a field path, unless it is <c>this</c> or a local. Locals are safe because
    /// nothing else can assign them; object locals can't even be passed by <c>ref</c>.
    /// </summary>
    static BoundExpression? PinRoot(BoundExpression place)
    {
        var current = place;
        while (current is BoundFieldAccess field)
        {
            if (field.Receiver.Type.IsReference)
                return IsStable(field.Receiver) ? null : field.Receiver;
            current = field.Receiver;
        }
        return null;
    }

    static bool IsStable(BoundExpression expression) => expression is BoundThis or BoundLocalAccess;

    /// <summary>Whether releasing a value of the type may destroy an object.</summary>
    static bool MayHoldReferences(VplType type) => MayHoldReferences(type, []);

    static bool MayHoldReferences(VplType type, HashSet<VplType> visiting)
    {
        if (type.IsReference || type.IsTypeParameter)
            return true;
        if (!type.IsStruct || !visiting.Add(type))
            return false;
        var map = TypeMap.For(type);
        return type.Symbol!.Fields.Any(f => MayHoldReferences(map.Apply(f.Type), visiting));
    }

    /// <summary>
    /// VPL evaluates left to right, but C++ leaves the order of operands and arguments unspecified.
    /// When the order is observable, evaluate the operands into temporaries inside an
    /// immediately-invoked lambda, which the C++ optimizer inlines away. Operands passed by
    /// reference are bound with <c>auto&amp;&amp;</c> so that the callee still sees the original place.
    /// </summary>
    string Ordered(IReadOnlyList<Operand> operands, Func<IReadOnlyList<string>, string> combine)
    {
        if (!NeedsOrdering(operands))
        {
            // A temporary pin lives until the end of the full expression, which includes the call.
            return combine([.. operands.Select(o =>
            {
                var text = OperandText(o, o.PinRoot is { } root ? $"vpl::pin({Expression(root)})" : null);
                return o.Keep ? $"vpl::keep({text})" : text;
            })]);
        }

        var body = new StringBuilder("[&] { ");
        var temps = new List<string>();
        foreach (var operand in operands)
        {
            string? pin = null;
            if (operand.PinRoot is { } root)
            {
                pin = NewTemp();
                body.Append($"auto {pin} = {Expression(root)}; ");
            }
            var temp = NewTemp();
            body.Append($"{(operand.ByReference ? "auto&&" : "auto")} {temp} = {OperandText(operand, pin)}; ");
            temps.Add(temp);
        }
        return body.Append($"return {combine(temps)}; }}()").ToString();
    }

    string OperandText(Operand operand, string? pinRootText)
    {
        if (pinRootText is not null)
            replacements[operand.PinRoot!] = pinRootText;
        var text = operand.ByReference ? Place(operand.Expression) : Expression(operand.Expression);
        if (pinRootText is not null)
            replacements.Remove(operand.PinRoot!);
        return operand.PinValue ? $"vpl::pin({text})" : text;
    }

    string Ordered(BoundExpression left, BoundExpression right, Func<IReadOnlyList<string>, string> combine) =>
        Ordered([new Operand(left, false), new Operand(right, false)], combine);

    bool NeedsOrdering(IReadOnlyList<Operand> operands)
    {
        for (int i = 0; i < operands.Count; i++)
        {
            for (int j = i + 1; j < operands.Count; j++)
            {
                if (Conflicts(operands[i], operands[j]))
                    return true;
            }
        }
        return false;
    }

    // Two effects (calls, panics) must stay in order, and so must a write and a read of the same
    // state. Any call may write any object, so object fields count as read by every call.
    bool Conflicts(Operand a, Operand b) =>
        (HasEffects(a.Expression) && HasEffects(b.Expression))
        || (Writes(a.Expression) && Reads(b, ReadsState))
        || (Writes(b.Expression) && Reads(a, ReadsState))
        || (WritesHeap(a.Expression) && Reads(b, ReadsHeap))
        || (WritesHeap(b.Expression) && Reads(a, ReadsHeap));

    // Binding a reference to a place reads only the objects the path goes through; the callee reads the rest later.
    static bool Reads(Operand operand, Func<BoundExpression, bool> reads) =>
        operand.ByReference && !operand.PinValue && IsPlace(operand.Expression)
            ? operand.PinRoot is { } root && reads(root)
            : reads(operand.Expression);

    static bool IsPlace(BoundExpression expression) => expression switch
    {
        BoundLocalAccess or BoundThis => true,
        BoundFieldAccess { Receiver.Type.IsReference: true } => true,
        BoundFieldAccess field => IsPlace(field.Receiver),
        _ => false,
    };

    static IEnumerable<BoundExpression> Children(BoundExpression expression) => expression switch
    {
        BoundUnary unary => [unary.Operand],
        BoundBinary binary => [binary.Left, binary.Right],
        BoundCall call => call.Receiver is null ? call.Arguments : [call.Receiver, .. call.Arguments],
        BoundConstruction construction => [.. construction.Arguments, .. construction.Initializers.Select(i => i.Value)],
        BoundNew creation => creation.Arguments,
        BoundConversion conversion => [conversion.Operand],
        BoundConditional conditional => [conditional.Condition, conditional.WhenTrue, conditional.WhenFalse],
        BoundFieldAccess field => [field.Receiver],
        BoundNonNull nonNull => [nonNull.Operand],
        BoundCoalesce coalesce => [coalesce.Left, coalesce.Right],
        BoundConditionalAccess access => [access.Receiver, access.WhenNotNull],
        BoundIs pattern => [pattern.Operand],
        _ => [],
    };

    bool HasEffects(BoundExpression expression) => expression switch
    {
        BoundCall or BoundNew or BoundNonNull => true,
        BoundIs { Binding: not null } => true,
        BoundConstruction construction when !construction.Constructor.Symbol.IsImplicit
            || NeedsDefaultCode(construction.Type) => true,
        BoundBinary binary when MayPanic(binary) => true,
        BoundUnary { Operator: BoundUnaryOperator.Negate } unary when unary.Type.IsInteger => true,
        _ => Children(expression).Any(HasEffects),
    };

    /// <summary>Whether evaluating the expression may modify locals, parameters, or fields of values.</summary>
    static bool Writes(BoundExpression expression) => expression switch
    {
        BoundCall call when call.Method.Symbol.Parameters.Any(p => p.RefKind == RefKind.Ref)
            || (call.Receiver is not null && !call.Receiver.Type.IsReference && !call.Method.Symbol.IsReadOnly) => true,
        BoundConstruction construction when construction.Constructor.Symbol.Parameters.Any(p => p.RefKind == RefKind.Ref) => true,
        BoundNew creation when creation.Constructor.Symbol.Parameters.Any(p => p.RefKind == RefKind.Ref) => true,
        BoundIs { Binding: not null } => true,
        _ => Children(expression).Any(Writes),
    };

    /// <summary>Whether evaluating the expression may run user code, which can modify any object.</summary>
    static bool WritesHeap(BoundExpression expression) => expression switch
    {
        BoundCall { Method.Symbol.IsBuiltin: false } or BoundNew => true,
        BoundConstruction construction when !construction.Constructor.Symbol.IsImplicit => true,
        _ => Children(expression).Any(WritesHeap),
    };

    static bool ReadsState(BoundExpression expression) =>
        expression is BoundLocalAccess or BoundThis or BoundFieldAccess || Children(expression).Any(ReadsState);

    /// <summary>
    /// Whether the expression reads storage that a call could change: fields of objects, and
    /// whatever a <c>ref</c>/<c>in</c> parameter or a struct method's <c>this</c> refers to,
    /// which may be inside an object.
    /// </summary>
    static bool ReadsHeap(BoundExpression expression) => expression switch
    {
        BoundFieldAccess { Receiver.Type.IsReference: true } => true,
        BoundLocalAccess { Local.RefKind: not RefKind.None } => true,
        BoundThis { Type.IsStruct: true } => true,
        _ => Children(expression).Any(ReadsHeap),
    };

    static bool MayPanic(BoundBinary binary) => binary.Left.Type.IsInteger && binary.Operator switch
    {
        BoundBinaryOperator.Add or BoundBinaryOperator.Subtract or BoundBinaryOperator.Multiply => true,
        BoundBinaryOperator.Divide or BoundBinaryOperator.Remainder =>
            binary.Right is not BoundLiteral { Value: int and not 0 and not -1 } and not BoundLiteral { Value: long and not 0L and not -1L },
        _ => false,
    };

    string Unary(BoundUnary unary)
    {
        var operand = Expression(unary.Operand);
        return unary.Operator switch
        {
            BoundUnaryOperator.Negate when unary.Type.IsInteger => $"vpl::neg({operand}, {SourceLocation(unary.Location)})",
            BoundUnaryOperator.Negate => $"(-{operand})",
            BoundUnaryOperator.LogicalNot => $"(!{operand})",
            BoundUnaryOperator.BitwiseNot => $"static_cast<{CppType(unary.Type)}>(~{operand})",
            _ => throw new InvalidOperationException($"unexpected unary operator {unary.Operator}"),
        };
    }

    string Binary(BoundBinary binary)
    {
        if (binary.Operator is BoundBinaryOperator.LogicalAnd or BoundBinaryOperator.LogicalOr)
        {
            var symbol = binary.Operator == BoundBinaryOperator.LogicalAnd ? "&&" : "||";
            return $"({Expression(binary.Left)} {symbol} {Expression(binary.Right)})";
        }
        if (binary.Left.Type.IsReference || binary.Left.Type == VplType.Null)
        {
            var symbol = binary.Operator == BoundBinaryOperator.Equal ? "==" : "!=";
            return Ordered(binary.Left, binary.Right, operands => $"(vpl::identity({operands[0]}) {symbol} vpl::identity({operands[1]}))");
        }
        return Ordered(binary.Left, binary.Right, operands => BinaryText(binary, operands[0], operands[1]));
    }

    string BinaryText(BoundBinary binary, string left, string right)
    {
        var operandType = binary.Left.Type;
        var location = SourceLocation(binary.Location);
        if (operandType.IsInteger)
        {
            switch (binary.Operator)
            {
                case BoundBinaryOperator.Add: return $"vpl::add({left}, {right}, {location})";
                case BoundBinaryOperator.Subtract: return $"vpl::sub({left}, {right}, {location})";
                case BoundBinaryOperator.Multiply: return $"vpl::mul({left}, {right}, {location})";
                case BoundBinaryOperator.Divide: return $"vpl::div({left}, {right}, {location})";
                case BoundBinaryOperator.Remainder: return $"vpl::rem({left}, {right}, {location})";
                case BoundBinaryOperator.ShiftLeft: return $"vpl::shl({left}, {right})";
                case BoundBinaryOperator.ShiftRight: return $"vpl::shr({left}, {right})";
            }
        }
        if (operandType.IsFloatingPoint && binary.Operator == BoundBinaryOperator.Remainder)
            return $"std::fmod({left}, {right})";

        var cppOperator = binary.Operator switch
        {
            BoundBinaryOperator.Add => "+",
            BoundBinaryOperator.Subtract => "-",
            BoundBinaryOperator.Multiply => "*",
            BoundBinaryOperator.Divide => "/",
            BoundBinaryOperator.BitwiseAnd => "&",
            BoundBinaryOperator.BitwiseOr => "|",
            BoundBinaryOperator.BitwiseXor => "^",
            BoundBinaryOperator.Equal => "==",
            BoundBinaryOperator.NotEqual => "!=",
            BoundBinaryOperator.Less => "<",
            BoundBinaryOperator.LessOrEqual => "<=",
            BoundBinaryOperator.Greater => ">",
            BoundBinaryOperator.GreaterOrEqual => ">=",
            _ => throw new InvalidOperationException($"unexpected binary operator {binary.Operator}"),
        };

        // C++ promotes bitwise operands to int; cast back so overloads see the VPL type.
        if (binary.Operator is BoundBinaryOperator.BitwiseAnd or BoundBinaryOperator.BitwiseOr or BoundBinaryOperator.BitwiseXor)
            return $"static_cast<{CppType(binary.Type)}>({left} {cppOperator} {right})";
        return $"({left} {cppOperator} {right})";
    }

    Operand ReceiverOperand(BoundExpression receiver)
    {
        var type = receiver.Type;
        if (type.IsReference || type.IsTypeParameter)
            return new Operand(receiver, ByReference: true, PinRoot(receiver), PinValue: !IsStable(receiver));
        return new Operand(receiver, ByReference: true, PinRoot(receiver));
    }

    Operand ArgumentOperand(BoundExpression argument, RefKind refKind) =>
        refKind != RefKind.None ? new Operand(argument, true, PinRoot(argument))
        : new Operand(argument, false, Keep: !IsStable(argument) && MayHoldReferences(argument.Type));

    string Call(BoundCall call)
    {
        var method = call.Method;
        var function = method.Symbol;
        var operands = new List<Operand>();
        // `this` is never reassigned, so it needs no operand of its own.
        bool receiverOperand = call.Receiver is not null && call.Receiver is not BoundThis;
        if (receiverOperand)
            operands.Add(ReceiverOperand(call.Receiver!));
        operands.AddRange(call.Arguments.Select((argument, i) => ArgumentOperand(argument, method.ParameterRefKind(i))));
        var location = function.PassesLocation ? SourceLocation(call.Location) : null;

        // Explicit template arguments keep C++ from deducing differently than VPL resolved.
        var typeArguments = TypeArgumentList(method.TypeArguments);
        // `.template` is required for a member template of a dependent type and harmless otherwise.
        var memberName = (typeArguments.Length > 0 ? "template " : "") + MethodName(function) + typeArguments;

        return Ordered(operands, parts =>
        {
            var arguments = parts.Skip(receiverOperand ? 1 : 0);
            if (location is not null)
                arguments = arguments.Append(location);
            var argumentText = string.Join(", ", arguments);

            if (function.BuiltinCppName is { } builtin)
                return $"{builtin}({argumentText})";
            if (function.ContainingType is null)
                return $"{FunctionName(function)}{typeArguments}({argumentText})";
            if (function.IsStatic)
                return $"{ObjectType(method.Owner!)}::{memberName}({argumentText})";
            return $"{(receiverOperand ? ReceiverText(call, parts[0]) : ThisReceiverText(call))}{memberName}({argumentText})";
        });
    }

    /// <summary>The receiver and member operator. Calls go through the declaring type; see <c>vpl::as</c>.</summary>
    string ReceiverText(BoundCall call, string receiver)
    {
        var receiverType = call.Receiver!.Type;
        var declaring = ObjectType(call.Method.Owner!);
        if (receiverType.IsTypeParameter)
            return $"vpl::bound<{declaring}>({receiver}).";
        if (receiverType.IsReference)
            return receiverType.NonNull.Symbol == call.Method.Owner!.Symbol ? $"{receiver}->" : $"vpl::as<{declaring}>({receiver})->";
        return receiver + ".";
    }

    string ThisReceiverText(BoundCall call)
    {
        var declaring = ObjectType(call.Method.Owner!);
        if (call.IsSuperCall)
            return $"this->{declaring}::";
        if (context == Context.StructConstructor)
            return "self.";
        if (call.Method.Owner!.Symbol == currentType)
            return "this->";
        return $"static_cast<{declaring}*>(this)->";
    }

    string Construction(BoundConstruction construction)
    {
        var type = CppType(construction.Type);
        var constructor = construction.Constructor;
        var operands = construction.Arguments
            .Select((argument, i) => ArgumentOperand(argument, constructor.ParameterRefKind(i)))
            .ToList();
        var created = Ordered(operands, arguments => constructor.Symbol.IsImplicit
            ? DefaultValue(construction.Type)
            : $"{type}::make({string.Join(", ", arguments)})");
        if (construction.Initializers.Count == 0)
            return created;

        var temp = NewTemp();
        var body = new StringBuilder($"[&] {{ {type} {temp} = {created}; ");
        foreach (var initializer in construction.Initializers)
            body.Append($"{temp}.{FieldName(initializer.Field)} = {Expression(initializer.Value)}; ");
        return body.Append($"return {temp}; }}()").ToString();
    }

    string New(BoundNew creation)
    {
        var constructor = creation.Constructor;
        var operands = creation.Arguments
            .Select((argument, i) => ArgumentOperand(argument, constructor.ParameterRefKind(i)))
            .ToList();
        return Ordered(operands, arguments => $"vpl::adopt(new {ObjectType(creation.Type)}({string.Join(", ", arguments)}))");
    }

    string Coalesce(BoundCoalesce coalesce)
    {
        var temp = NewTemp();
        return $"[&]() -> {CppType(coalesce.Type)} {{ auto {temp} = {Expression(coalesce.Left)}; if ({temp}) {{ return {temp}; }} return {Expression(coalesce.Right)}; }}()";
    }

    string ConditionalAccess(BoundConditionalAccess access)
    {
        var value = LocalName(access.Value);
        var receiver = Expression(access.Receiver);
        var member = Expression(access.WhenNotNull);
        if (access.Type == VplType.Void)
            return $"[&] {{ auto {value} = {receiver}; if ({value}) {{ {member}; }} }}()";
        return $"[&]() -> {CppType(access.Type)} {{ auto {value} = {receiver}; if (!{value}) {{ return nullptr; }} return {member}; }}()";
    }

    string Is(BoundIs pattern)
    {
        var target = ObjectType(pattern.Target);
        var operand = Expression(pattern.Operand);
        return pattern.Binding is { } binding
            ? $"vpl::is<{target}>({operand}, {LocalName(binding)})"
            : $"vpl::is<{target}>({operand})";
    }

    string Conversion(BoundConversion conversion)
    {
        var from = conversion.Operand.Type;
        var to = conversion.Type;
        var operand = Expression(conversion.Operand);
        if (from == VplType.Null)
            return $"{CppType(to)}()";
        if (to.IsReference)
            return CppType(from) == CppType(to) ? operand : $"{CppType(to)}({operand})";
        if (from.IsFloatingPoint && to.IsInteger)
            return $"vpl::f2i<{CppType(to)}>({operand})";
        if (from == VplType.Double && to == VplType.Float)
            return $"vpl::d2f({operand})";
        return $"static_cast<{CppType(to)}>({operand})";
    }

    static string Literal(BoundLiteral literal) => literal.Value switch
    {
        bool b => b ? "true" : "false",
        int i when i == int.MinValue => "INT32_MIN",
        int i => i < 0 ? $"({i})" : i.ToString(CultureInfo.InvariantCulture),
        long l when l == long.MinValue => "INT64_MIN",
        long l => l < 0 ? $"(-INT64_C({-l}))" : $"INT64_C({l})",
        float f => FloatText(f.ToString("R", CultureInfo.InvariantCulture)) + "f",
        double d => FloatText(d.ToString("R", CultureInfo.InvariantCulture)),
        string s => $"vpl::String{{{CppStringLiteral(s)}, {Encoding.UTF8.GetByteCount(s)}}}",
        _ => throw new InvalidOperationException($"unexpected literal {literal.Value.GetType().Name}"),
    };

    static string FloatText(string text) => text.Contains('.') || text.Contains('E') ? text : text + ".0";

    static string SourceLocation(Location location)
    {
        var (line, column) = location.LineColumn;
        return CppStringLiteral($"{location.Source.FileName}:{line}:{column}");
    }

    static string CppStringLiteral(string value)
    {
        var result = new StringBuilder("\"");
        foreach (byte b in Encoding.UTF8.GetBytes(value))
        {
            switch (b)
            {
                case (byte)'"':
                    result.Append("\\\"");
                    break;
                case (byte)'\\':
                    result.Append("\\\\");
                    break;
                case >= 0x20 and < 0x7F:
                    result.Append((char)b);
                    break;
                default:
                    // Octal escapes stop after three digits; hex escapes would swallow following hex characters.
                    result.Append('\\').Append(System.Convert.ToString(b, 8).PadLeft(3, '0'));
                    break;
            }
        }
        return result.Append('"').ToString();
    }
