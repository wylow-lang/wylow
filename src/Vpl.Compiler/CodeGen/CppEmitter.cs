using System.Globalization;
using System.Text;
using Vpl.Compiler.Semantics;
using Vpl.Compiler.Syntax;
using Vpl.Compiler.Text;

namespace Vpl.Compiler.CodeGen;

/// <summary>
/// Translates a checked program to C++. Every safety decision has already been made by the
/// binder and flow analysis; this class must never emit C++ whose behavior is undefined.
/// </summary>
/// <remarks>
/// Structs stay C++ aggregates: constructors become static <c>make</c> functions and field
/// initializers run in <c>make_default</c>, so struct definitions only need their fields' types.
/// Generics become C++ templates; the binder has already checked every instantiation is valid.
/// </remarks>
public sealed class CppEmitter
{
    enum Context { Free, Method, Constructor }

    readonly record struct Operand(BoundExpression Expression, bool ByReference);

    readonly StringBuilder output = new();
    readonly Dictionary<StructSymbol, bool> needsDefaultFunction = new();
    int indent;
    int tempCounter;
    Context context;

    public string Emit(BoundProgram program)
    {
        var main = program.Main ?? throw new ArgumentException("program has no main function", nameof(program));

        Line($"// Generated by vpl from {program.Source.FileName}. Do not edit.");
        Line("#include \"vpl.h\"");

        if (program.Structs.Count > 0)
        {
            Line();
            foreach (var s in program.Structs)
                Line(TemplatePrefix(s.TypeParameters) + $"struct {StructName(s)};");
        }

        Line();
        foreach (var function in program.Functions.Where(f => f.Symbol.ContainingStruct is null))
            Line(TemplatePrefix(function.Symbol.TypeParameters) + DefinitionSignature(function.Symbol) + ";");

        foreach (var s in DependencyOrder(program.Structs))
        {
            Line();
            EmitStructDefinition(s);
        }

        foreach (var s in program.Structs.Where(NeedsDefaultFunction))
        {
            Line();
            EmitDefaultFunction(s);
        }

        foreach (var function in program.Functions)
        {
            Line();
            EmitFunction(function);
        }

        Line();
        Line("int main()");
        Line("{");
        indent++;
        Line("vpl::init();");
        if (main.ReturnType == VplType.Int)
        {
            Line($"return {FunctionName(main)}();");
        }
        else
        {
            Line($"{FunctionName(main)}();");
            Line("return 0;");
        }
        indent--;
        Line("}");
        return output.ToString();
    }

    void Line(string text = "")
    {
        if (text.Length > 0)
            output.Append(' ', indent * 4).Append(text);
        output.Append('\n');
    }

    string NewTemp() => $"tmp_{tempCounter++}";

    // Prefixes keep VPL names from colliding with C++ keywords, the runtime, and each other.
    static string FunctionName(FunctionSymbol function) => "fn_" + function.Name;
    static string MethodName(FunctionSymbol method) => "m_" + method.Name;
    static string LocalName(LocalSymbol local) => "l_" + local.Name;
    static string FieldName(FieldSymbol field) => "f_" + field.Name;
    static string StructName(StructSymbol s) => "s_" + s.Name;
    static string TypeParameterName(TypeParameterSymbol parameter) => "t_" + parameter.Name;

    static string TemplatePrefix(IReadOnlyList<TypeParameterSymbol> parameters) => parameters.Count == 0
        ? ""
        : $"template <{string.Join(", ", parameters.Select(p => "class " + TypeParameterName(p)))}> ";

    static string TypeArgumentList(IReadOnlyList<VplType> arguments) =>
        arguments.Count == 0 ? "" : $"<{string.Join(", ", arguments.Select(CppType))}>";

    static string CppType(VplType type)
    {
        if (type.TypeParameter is { } parameter) return TypeParameterName(parameter);
        if (type.Struct is { } s) return StructName(s) + TypeArgumentList(type.TypeArguments);
        if (type == VplType.Void) return "void";
        if (type == VplType.Bool) return "bool";
        if (type == VplType.Int) return "int32_t";
        if (type == VplType.Long) return "int64_t";
        if (type == VplType.Float) return "float";
        if (type == VplType.Double) return "double";
        if (type == VplType.String) return "vpl::String";
        throw new InvalidOperationException($"no C++ type for '{type}'");
    }

    // ---- Structs ----

    /// <summary>Orders struct definitions so each comes after every struct its fields mention, including in type arguments.</summary>
    static List<StructSymbol> DependencyOrder(IReadOnlyList<StructSymbol> structs)
    {
        var ordered = new List<StructSymbol>();
        var visited = new HashSet<StructSymbol>();

        void VisitType(VplType type)
        {
            if (type.Struct is { } s)
                Visit(s);
            foreach (var argument in type.TypeArguments)
                VisitType(argument);
        }

        void Visit(StructSymbol s)
        {
            if (!visited.Add(s))
                return;
            foreach (var field in s.Fields)
                VisitType(field.Type);
            ordered.Add(s);
        }

        foreach (var s in structs)
            Visit(s);
        return ordered;
    }

    /// <summary>
    /// Whether default construction must run code rather than just zero-initialize. Generic structs
    /// always get a <c>make_default</c>, since their type arguments may need one.
    /// </summary>
    bool NeedsDefaultFunction(StructSymbol s)
    {
        if (!needsDefaultFunction.TryGetValue(s, out bool needs))
        {
            needsDefaultFunction[s] = false;
            needs = s.IsGeneric || s.Fields.Any(f => f.Initializer is not null || NeedsDefaultCode(f.Type));
            needsDefaultFunction[s] = needs;
        }
        return needs;
    }

    bool NeedsDefaultCode(VplType type) =>
        type.IsTypeParameter || (type.Struct is { } s && NeedsDefaultFunction(s));

    string DefaultValue(VplType type)
    {
        if (type.IsTypeParameter)
            return $"vpl::default_value<{CppType(type)}>()";
        return NeedsDefaultFunction(type.Struct!) ? $"{CppType(type)}::make_default()" : $"{CppType(type)}{{}}";
    }

    void EmitStructDefinition(StructSymbol s)
    {
        var name = StructName(s);
        if (s.IsGeneric)
            Line(TemplatePrefix(s.TypeParameters).TrimEnd());
        Line($"struct {name}");
        Line("{");
        indent++;
        foreach (var field in s.Fields)
            Line($"{CppType(field.Type)} {FieldName(field)}{{}};");
        if (NeedsDefaultFunction(s))
            Line($"static {name} make_default();");
        foreach (var member in s.Members)
            Line(TemplatePrefix(member.TypeParameters) + MemberDeclaration(member) + ";");
        // In a template, a defaulted == whose members lack == is deleted rather than an error.
        if (s.IsGeneric || Conversions.SupportsEquality(s.Type))
            Line($"bool operator==(const {name}&) const = default;");
        indent--;
        Line("};");
    }

    void EmitDefaultFunction(StructSymbol s)
    {
        var type = CppType(s.Type);
        context = Context.Free;
        if (s.IsGeneric)
            Line(TemplatePrefix(s.TypeParameters).TrimEnd());
        Line($"{type} {type}::make_default()");
        Line("{");
        indent++;
        Line($"{type} self{{}};");
        foreach (var field in s.Fields)
        {
            if (field.Initializer is { } initializer)
                Line($"self.{FieldName(field)} = {Expression(initializer)};");
            else if (NeedsDefaultCode(field.Type))
                Line($"self.{FieldName(field)} = {DefaultValue(field.Type)};");
        }
        Line("return self;");
        indent--;
        Line("}");
    }

    // ---- Functions ----

    static string Parameters(FunctionSymbol function) => string.Join(", ", function.Parameters.Select(p =>
    {
        var type = CppType(p.Type);
        var declared = p.RefKind switch
        {
            RefKind.Ref => type + "&",
            RefKind.In => $"const {type}&",
            _ => type,
        };
        return $"{declared} {LocalName(p)}";
    }));

    static string MemberDeclaration(FunctionSymbol member)
    {
        if (member.IsConstructor)
            return $"static {StructName(member.ContainingStruct!)} make({Parameters(member)})";
        var signature = $"{CppType(member.ReturnType)} {MethodName(member)}({Parameters(member)})";
        return member.IsStatic ? "static " + signature : signature + (member.IsReadOnly ? " const" : "");
    }

    static string DefinitionSignature(FunctionSymbol function)
    {
        if (function.ContainingStruct is not { } s)
            return $"{CppType(function.ReturnType)} {FunctionName(function)}({Parameters(function)})";
        var owner = CppType(s.Type);
        if (function.IsConstructor)
            return $"{owner} {owner}::make({Parameters(function)})";
        var signature = $"{CppType(function.ReturnType)} {owner}::{MethodName(function)}({Parameters(function)})";
        return function.IsReadOnly ? signature + " const" : signature;
    }

    void EmitFunction(BoundFunction function)
    {
        var symbol = function.Symbol;
        context = symbol.IsConstructor ? Context.Constructor : symbol.IsInstanceMethod ? Context.Method : Context.Free;

        if (symbol.ContainingStruct is { IsGeneric: true } owner)
            Line(TemplatePrefix(owner.TypeParameters).TrimEnd());
        if (symbol.IsGeneric)
            Line(TemplatePrefix(symbol.TypeParameters).TrimEnd());
        Line(DefinitionSignature(symbol));
        Line("{");
        indent++;
        if (symbol.IsConstructor)
        {
            var type = symbol.ContainingStruct!.Type;
            Line($"{CppType(type)} self = {DefaultValue(type)};");
        }
        foreach (var statement in function.Body.Statements)
            Statement(statement);
        if (symbol.IsConstructor)
        {
            Line("return self;");
        }
        else if (symbol.ReturnType != VplType.Void)
        {
            var body = function.Body.Location;
            Line($"vpl::unreachable({SourceLocation(body with { Span = new TextSpan(body.Span.End - 1, 1) })});");
        }
        indent--;
        Line("}");
        context = Context.Free;
    }

    // ---- Statements ----

    void Statement(BoundStatement statement)
    {
        switch (statement)
        {
            case BoundBlock block:
                Line("{");
                indent++;
                foreach (var s in block.Statements)
                    Statement(s);
                indent--;
                Line("}");
                break;
            case BoundVariableDeclaration declaration:
                var initializer = declaration.Initializer is null ? "{}" : " = " + Expression(declaration.Initializer);
                Line($"{CppType(declaration.Local.Type)} {LocalName(declaration.Local)}{initializer};");
                break;
            case BoundAssignment or BoundExpressionStatement:
                Line(SimpleStatement(statement) + ";");
                break;
            case BoundIf ifStatement:
                Line($"if ({Expression(ifStatement.Condition)})");
                Statement(ifStatement.Then);
                if (ifStatement.Else is not null)
                {
                    Line("else");
                    Statement(ifStatement.Else);
                }
                break;
            case BoundWhile whileStatement:
                Line($"while ({Expression(whileStatement.Condition)})");
                Statement(whileStatement.Body);
                break;
            case BoundFor forStatement:
                Line("{");
                indent++;
                if (forStatement.Initializer is not null)
                    Statement(forStatement.Initializer);
                var condition = forStatement.Condition is null ? "" : Expression(forStatement.Condition);
                var update = forStatement.Update is null ? "" : SimpleStatement(forStatement.Update);
                Line($"for (; {condition}; {update})");
                Statement(forStatement.Body);
                indent--;
                Line("}");
                break;
            case BoundReturn returnStatement:
                if (context == Context.Constructor)
                    Line("return self;");
                else
                    Line(returnStatement.Value is null ? "return;" : $"return {Expression(returnStatement.Value)};");
                break;
            case BoundBreak:
                Line("break;");
                break;
            case BoundContinue:
                Line("continue;");
                break;
            default:
                throw new InvalidOperationException($"unexpected statement {statement.GetType().Name}");
        }
    }

    // C++17 evaluates the right side of '=' before the left; the target is a pure path, so that is fine.
    string SimpleStatement(BoundStatement statement) => statement switch
    {
        BoundAssignment assignment => $"{Expression(assignment.Target)} = {Expression(assignment.Value)}",
        BoundExpressionStatement expressionStatement => Expression(expressionStatement.Expression),
        _ => throw new InvalidOperationException($"unexpected simple statement {statement.GetType().Name}"),
    };

    // ---- Expressions ----

    string Expression(BoundExpression expression) => expression switch
    {
        BoundLiteral literal => Literal(literal),
        BoundLocalAccess access => LocalName(access.Local),
        BoundThis => context == Context.Constructor ? "self" : "(*this)",
        BoundFieldAccess field => FieldAccess(field),
        BoundUnary unary => Unary(unary),
        BoundBinary binary => Binary(binary),
        BoundCall call => Call(call),
        BoundConstruction construction => Construction(construction),
        BoundConversion conversion => Conversion(conversion),
        BoundConditional conditional =>
            $"({Expression(conditional.Condition)} ? {Expression(conditional.WhenTrue)} : {Expression(conditional.WhenFalse)})",
        _ => throw new InvalidOperationException($"unexpected expression {expression.GetType().Name}"),
    };

    string FieldAccess(BoundFieldAccess field)
    {
        if (field.Receiver is BoundThis)
            return (context == Context.Constructor ? "self." : "this->") + FieldName(field.Field);
        return $"{Expression(field.Receiver)}.{FieldName(field.Field)}";
    }

    /// <summary>
    /// VPL evaluates left to right, but C++ leaves the order of operands and arguments unspecified.
    /// When the order is observable, evaluate the operands into temporaries inside an
    /// immediately-invoked lambda, which the C++ optimizer inlines away. Operands passed by
    /// reference are bound with <c>auto&amp;&amp;</c> so that the callee still sees the original place.
    /// </summary>
    string Ordered(IReadOnlyList<Operand> operands, Func<IReadOnlyList<string>, string> combine)
    {
        if (!NeedsOrdering(operands))
            return combine([.. operands.Select(o => Expression(o.Expression))]);

        var body = new StringBuilder("[&] { ");
        var temps = new List<string>();
        foreach (var operand in operands)
        {
            var temp = NewTemp();
            body.Append($"{(operand.ByReference ? "auto&&" : "auto")} {temp} = {Expression(operand.Expression)}; ");
            temps.Add(temp);
        }
        return body.Append($"return {combine(temps)}; }}()").ToString();
    }

    string Ordered(BoundExpression left, BoundExpression right, Func<IReadOnlyList<string>, string> combine) =>
        Ordered([new Operand(left, false), new Operand(right, false)], combine);

    bool NeedsOrdering(IReadOnlyList<Operand> operands)
    {
        for (int i = 0; i < operands.Count; i++)
        {
            for (int j = i + 1; j < operands.Count; j++)
            {
                if (Conflicts(operands[i], operands[j]))
                    return true;
            }
        }
        return false;
    }

    // Two effects (calls, panics) must stay in order, and so must a write and a read of the same state.
    bool Conflicts(Operand a, Operand b) =>
        (HasEffects(a.Expression) && HasEffects(b.Expression))
        || (Writes(a.Expression) && Reads(b))
        || (Writes(b.Expression) && Reads(a));

    // Binding a reference to a place reads nothing; the callee reads it later.
    static bool Reads(Operand operand) =>
        !(operand.ByReference && IsPlace(operand.Expression)) && ReadsState(operand.Expression);

    static bool IsPlace(BoundExpression expression) => expression switch
    {
        BoundLocalAccess or BoundThis => true,
        BoundFieldAccess field => IsPlace(field.Receiver),
        _ => false,
    };

    static IEnumerable<BoundExpression> Children(BoundExpression expression) => expression switch
    {
        BoundUnary unary => [unary.Operand],
        BoundBinary binary => [binary.Left, binary.Right],
        BoundCall call => call.Receiver is null ? call.Arguments : [call.Receiver, .. call.Arguments],
        BoundConstruction construction => [.. construction.Arguments, .. construction.Initializers.Select(i => i.Value)],
        BoundConversion conversion => [conversion.Operand],
        BoundConditional conditional => [conditional.Condition, conditional.WhenTrue, conditional.WhenFalse],
        BoundFieldAccess field => [field.Receiver],
        _ => [],
    };

    bool HasEffects(BoundExpression expression) => expression switch
    {
        BoundCall => true,
        BoundConstruction construction when !construction.Constructor.Symbol.IsImplicit
            || NeedsDefaultCode(construction.Type) => true,
        BoundBinary binary when MayPanic(binary) => true,
        BoundUnary { Operator: BoundUnaryOperator.Negate } unary when unary.Type.IsInteger => true,
        _ => Children(expression).Any(HasEffects),
    };

    /// <summary>Whether evaluating the expression may modify locals, parameters, or fields.</summary>
    static bool Writes(BoundExpression expression) => expression switch
    {
        BoundCall call when call.Method.Symbol.Parameters.Any(p => p.RefKind == RefKind.Ref)
            || (call.Receiver is not null && !call.Method.Symbol.IsReadOnly) => true,
        BoundConstruction construction when construction.Constructor.Symbol.Parameters.Any(p => p.RefKind == RefKind.Ref) => true,
        _ => Children(expression).Any(Writes),
    };

    static bool ReadsState(BoundExpression expression) =>
        expression is BoundLocalAccess or BoundThis or BoundFieldAccess || Children(expression).Any(ReadsState);

    static bool MayPanic(BoundBinary binary) => binary.Left.Type.IsInteger && binary.Operator switch
    {
        BoundBinaryOperator.Add or BoundBinaryOperator.Subtract or BoundBinaryOperator.Multiply => true,
        BoundBinaryOperator.Divide or BoundBinaryOperator.Remainder =>
            binary.Right is not BoundLiteral { Value: int and not 0 and not -1 } and not BoundLiteral { Value: long and not 0L and not -1L },
        _ => false,
    };

    string Unary(BoundUnary unary)
    {
        var operand = Expression(unary.Operand);
        return unary.Operator switch
        {
            BoundUnaryOperator.Negate when unary.Type.IsInteger => $"vpl::neg({operand}, {SourceLocation(unary.Location)})",
            BoundUnaryOperator.Negate => $"(-{operand})",
            BoundUnaryOperator.LogicalNot => $"(!{operand})",
            BoundUnaryOperator.BitwiseNot => $"static_cast<{CppType(unary.Type)}>(~{operand})",
            _ => throw new InvalidOperationException($"unexpected unary operator {unary.Operator}"),
        };
    }

    string Binary(BoundBinary binary)
    {
        if (binary.Operator is BoundBinaryOperator.LogicalAnd or BoundBinaryOperator.LogicalOr)
        {
            var symbol = binary.Operator == BoundBinaryOperator.LogicalAnd ? "&&" : "||";
            return $"({Expression(binary.Left)} {symbol} {Expression(binary.Right)})";
        }
        return Ordered(binary.Left, binary.Right, operands => BinaryText(binary, operands[0], operands[1]));
    }

    string BinaryText(BoundBinary binary, string left, string right)
    {
        var operandType = binary.Left.Type;
        var location = SourceLocation(binary.Location);
        if (operandType.IsInteger)
        {
            switch (binary.Operator)
            {
                case BoundBinaryOperator.Add: return $"vpl::add({left}, {right}, {location})";
                case BoundBinaryOperator.Subtract: return $"vpl::sub({left}, {right}, {location})";
                case BoundBinaryOperator.Multiply: return $"vpl::mul({left}, {right}, {location})";
                case BoundBinaryOperator.Divide: return $"vpl::div({left}, {right}, {location})";
                case BoundBinaryOperator.Remainder: return $"vpl::rem({left}, {right}, {location})";
                case BoundBinaryOperator.ShiftLeft: return $"vpl::shl({left}, {right})";
                case BoundBinaryOperator.ShiftRight: return $"vpl::shr({left}, {right})";
            }
        }
        if (operandType.IsFloatingPoint && binary.Operator == BoundBinaryOperator.Remainder)
            return $"std::fmod({left}, {right})";

        var cppOperator = binary.Operator switch
        {
            BoundBinaryOperator.Add => "+",
            BoundBinaryOperator.Subtract => "-",
            BoundBinaryOperator.Multiply => "*",
            BoundBinaryOperator.Divide => "/",
            BoundBinaryOperator.BitwiseAnd => "&",
            BoundBinaryOperator.BitwiseOr => "|",
            BoundBinaryOperator.BitwiseXor => "^",
            BoundBinaryOperator.Equal => "==",
            BoundBinaryOperator.NotEqual => "!=",
            BoundBinaryOperator.Less => "<",
            BoundBinaryOperator.LessOrEqual => "<=",
            BoundBinaryOperator.Greater => ">",
            BoundBinaryOperator.GreaterOrEqual => ">=",
            _ => throw new InvalidOperationException($"unexpected binary operator {binary.Operator}"),
        };

        // C++ promotes bitwise operands to int; cast back so overloads see the VPL type.
        if (binary.Operator is BoundBinaryOperator.BitwiseAnd or BoundBinaryOperator.BitwiseOr or BoundBinaryOperator.BitwiseXor)
            return $"static_cast<{CppType(binary.Type)}>({left} {cppOperator} {right})";
        return $"({left} {cppOperator} {right})";
    }

    string Call(BoundCall call)
    {
        var method = call.Method;
        var function = method.Symbol;
        var operands = new List<Operand>();
        if (call.Receiver is not null)
            operands.Add(new Operand(call.Receiver, ByReference: true));
        operands.AddRange(call.Arguments.Select((argument, i) => new Operand(argument, method.ParameterRefKind(i) != RefKind.None)));
        var location = function.PassesLocation ? SourceLocation(call.Location) : null;

        // Explicit template arguments keep C++ from deducing differently than VPL resolved.
        var typeArguments = TypeArgumentList(method.TypeArguments);
        // `.template` is required for a member template of a dependent type and harmless otherwise.
        var memberName = (typeArguments.Length > 0 ? "template " : "") + MethodName(function) + typeArguments;

        return Ordered(operands, parts =>
        {
            var arguments = parts.Skip(call.Receiver is null ? 0 : 1);
            if (location is not null)
                arguments = arguments.Append(location);
            var argumentText = string.Join(", ", arguments);

            if (function.BuiltinCppName is { } builtin)
                return $"{builtin}({argumentText})";
            if (function.ContainingStruct is null)
                return $"{FunctionName(function)}{typeArguments}({argumentText})";
            if (function.IsStatic)
                return $"{CppType(method.Owner!)}::{memberName}({argumentText})";
            var receiver = parts[0] == "(*this)" ? "this->" : parts[0] + ".";
            return $"{receiver}{memberName}({argumentText})";
        });
    }

    string Construction(BoundConstruction construction)
    {
        var type = CppType(construction.Type);
        var constructor = construction.Constructor;
        var operands = construction.Arguments
            .Select((argument, i) => new Operand(argument, constructor.ParameterRefKind(i) != RefKind.None))
            .ToList();
        var created = Ordered(operands, arguments => constructor.Symbol.IsImplicit
            ? DefaultValue(construction.Type)
            : $"{type}::make({string.Join(", ", arguments)})");
        if (construction.Initializers.Count == 0)
            return created;

        var temp = NewTemp();
        var body = new StringBuilder($"[&] {{ {type} {temp} = {created}; ");
        foreach (var initializer in construction.Initializers)
            body.Append($"{temp}.{FieldName(initializer.Field)} = {Expression(initializer.Value)}; ");
        return body.Append($"return {temp}; }}()").ToString();
    }

    string Conversion(BoundConversion conversion)
    {
        var from = conversion.Operand.Type;
        var to = conversion.Type;
        var operand = Expression(conversion.Operand);
        if (from.IsFloatingPoint && to.IsInteger)
            return $"vpl::f2i<{CppType(to)}>({operand})";
        if (from == VplType.Double && to == VplType.Float)
            return $"vpl::d2f({operand})";
        return $"static_cast<{CppType(to)}>({operand})";
    }

    static string Literal(BoundLiteral literal) => literal.Value switch
    {
        bool b => b ? "true" : "false",
        int i when i == int.MinValue => "INT32_MIN",
        int i => i < 0 ? $"({i})" : i.ToString(CultureInfo.InvariantCulture),
        long l when l == long.MinValue => "INT64_MIN",
        long l => l < 0 ? $"(-INT64_C({-l}))" : $"INT64_C({l})",
        float f => FloatText(f.ToString("R", CultureInfo.InvariantCulture)) + "f",
        double d => FloatText(d.ToString("R", CultureInfo.InvariantCulture)),
        string s => $"vpl::String{{{CppStringLiteral(s)}, {Encoding.UTF8.GetByteCount(s)}}}",
        _ => throw new InvalidOperationException($"unexpected literal {literal.Value.GetType().Name}"),
    };

    static string FloatText(string text) => text.Contains('.') || text.Contains('E') ? text : text + ".0";

    static string SourceLocation(Location location)
    {
        var (line, column) = location.LineColumn;
        return CppStringLiteral($"{location.Source.FileName}:{line}:{column}");
    }

    static string CppStringLiteral(string value)
    {
        var result = new StringBuilder("\"");
        foreach (byte b in Encoding.UTF8.GetBytes(value))
        {
            switch (b)
            {
                case (byte)'"':
                    result.Append("\\\"");
                    break;
                case (byte)'\\':
                    result.Append("\\\\");
                    break;
                case >= 0x20 and < 0x7F:
                    result.Append((char)b);
                    break;
                default:
                    // Octal escapes stop after three digits; hex escapes would swallow following hex characters.
                    result.Append('\\').Append(System.Convert.ToString(b, 8).PadLeft(3, '0'));
                    break;
            }
        }
        return result.Append('"').ToString();
    }
}
